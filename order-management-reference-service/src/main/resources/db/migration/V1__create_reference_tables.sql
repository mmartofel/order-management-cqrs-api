CREATE TABLE person (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR(100) NOT NULL,
    last_name  VARCHAR(100) NOT NULL,
    email      VARCHAR(255) NOT NULL,
    phone      VARCHAR(30),
    version    BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_person PRIMARY KEY (id),
    CONSTRAINT uk_person_email UNIQUE (email),
    CONSTRAINT ck_person_first_name CHECK (length(trim(first_name)) > 0),
    CONSTRAINT ck_person_last_name CHECK (length(trim(last_name)) > 0)
);

CREATE TABLE address (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    person_id   BIGINT       NOT NULL,
    street      VARCHAR(200) NOT NULL,
    city        VARCHAR(100) NOT NULL,
    postal_code VARCHAR(20)  NOT NULL,
    country     VARCHAR(2)   NOT NULL,
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_address PRIMARY KEY (id),
    CONSTRAINT fk_address_person FOREIGN KEY (person_id) REFERENCES person (id) ON DELETE RESTRICT,
    CONSTRAINT ck_address_country CHECK (country ~ '^[A-Z]{2}$')
);

CREATE INDEX ix_address_person_id ON address (person_id);

CREATE TABLE item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sku         VARCHAR(50)    NOT NULL,
    name        VARCHAR(200)   NOT NULL,
    description VARCHAR(2000),
    price       NUMERIC(12, 2) NOT NULL,
    version     BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT pk_item PRIMARY KEY (id),
    CONSTRAINT uk_item_sku UNIQUE (sku),
    CONSTRAINT ck_item_price CHECK (price > 0)
);
